"""Streamlit chat UI (Phase 8, docs/implementation.md).

This file only *displays* what :mod:`rag.validate` produced. The citation and
the freshness line are already rendered into ``payload.text`` by Python, from
the winning chunk's metadata, so the UI has no way to violate the response
contract (architecture.md 6.7).

Two invariants shape the code:

* Nothing typed here is written to disk. The chat thread lives in
  ``st.session_state`` only (FR-5.3, NFR-4).
* An answer is never faked. If ``ask`` raises, the user is told the assistant is
  unavailable; no fallback answer is invented (invariant I6).

Run it with ``streamlit run app.py``.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any, Callable

import streamlit as st

from rag.config import PROJECT_ROOT
from rag.pipeline import ask
from rag.schemas import Route

#: Product name shown as the page title and the browser tab.
PRODUCT_NAME = "HDFC Mutual Fund Facts Assistant"

#: The §11.3 disclaimer, verbatim. This constant is the single source of truth
#: for D5: the banner below and ``docs/disclaimer.md`` are both derived from it,
#: and a test fails if the committed file ever drifts from this text (FR-9.2).
DISCLAIMER = (
    "Facts-only. No investment advice.\n"
    "This assistant answers questions about publicly available mutual fund scheme "
    "information and always links its source. It does not recommend, compare, or rate "
    "schemes, and it does not provide returns, projections, or tax advice. Mutual fund "
    "investments are subject to market risks; read the scheme's SID/KIM and consult a "
    "SEBI-registered investment adviser before investing."
)

#: The three demo questions, which are also the demo script: two cited factual
#: answers and one refusal. These are the questions a reviewer will ask first, so
#: they are fixed rather than sampled.
EXAMPLE_QUESTIONS: tuple[str, ...] = (
    "What is the expense ratio of HDFC Large Cap Fund - Direct Growth?",
    "What is the lock-in period for HDFC ELSS Tax Saver Fund?",
    "Should I buy HDFC Small Cap Fund?",
)
assert len(EXAMPLE_QUESTIONS) == 3, "the brief mandates exactly 3 examples"

#: Routes whose payload is a refusal rather than an answer. Rendered distinctly
#: so a refusal never reads as a broken or empty answer.
REFUSAL_ROUTES = frozenset({Route.ADVICE, Route.PERFORMANCE, Route.OUT_OF_SCOPE})

#: Shown when the store is unusable, so the user is told how to fix it.
INGEST_HINT = "corpus not ingested - run: make ingest"

MANIFEST_PATH = PROJECT_ROOT / "data" / "manifest.json"
DISCLAIMER_PATH = PROJECT_ROOT / "docs" / "disclaimer.md"

_PREVIEW_CHARS = 200


# ---------------------------------------------------------------------------
# D5 deliverable
# ---------------------------------------------------------------------------
def disclaimer_document() -> str:
    """The ``docs/disclaimer.md`` body, derived from :data:`DISCLAIMER`."""
    return (
        "# D5 - disclaimer\n"
        "\n"
        "Generated from the `DISCLAIMER` constant in `app.py`, which is the single\n"
        "source of truth (FR-9.2). Do not edit this file by hand: edit the constant\n"
        "and re-run `python -c \"import app; app.write_disclaimer()\"`.\n"
        "\n"
        "## Text shown in the app\n"
        "\n"
        "```\n"
        f"{DISCLAIMER}\n"
        "```\n"
        "\n"
        "Source of truth: docs/PRD.md section 11.3.\n"
    )


def write_disclaimer(path: Path = DISCLAIMER_PATH) -> bool:
    """Write ``docs/disclaimer.md`` from the constant. Returns True if changed.

    Deliberately not called during a normal UI run: rendering the app must not
    touch the disk. The committed file and a test keep the two in step instead.
    """
    body = disclaimer_document()
    try:
        if path.is_file() and path.read_text(encoding="utf-8") == body:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return True


# ---------------------------------------------------------------------------
# Header
# ---------------------------------------------------------------------------
def _format_date(stamp: str) -> str:
    """``2026-09-27T08:44:24+00:00`` -> ``27 Sep 2026``."""
    try:
        return datetime.fromisoformat(stamp).strftime("%d %b %Y")
    except (TypeError, ValueError):
        return stamp or "unknown date"


def corpus_summary(manifest_path: Path = MANIFEST_PATH) -> str:
    """The scope chip, built from ``data/manifest.json`` rather than hardcoded."""
    try:
        data = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return INGEST_HINT

    documents = data.get("documents") or []
    if not documents:
        return INGEST_HINT

    n_documents = int(data.get("n_documents") or len(documents))
    schemes = {d.get("scheme") for d in documents if d.get("scheme")}
    stamp = data.get("generated_at") or max(
        (d.get("retrieved_at") or "" for d in documents), default=""
    )
    return (
        f"1 AMC · {len(schemes)} schemes · {n_documents} documents · "
        f"ingested {_format_date(stamp)}"
    )


def store_is_empty() -> bool:
    """Whether the vector store has nothing in it.

    Any failure to open the store counts as empty: a half-built store must
    produce the ingest hint rather than a stack trace.
    """
    try:
        from rag.config import load_config
        from rag.pipeline import collection

        return collection(load_config()).count() == 0
    except Exception:  # noqa: BLE001 - any store problem means we cannot serve
        return True


# ---------------------------------------------------------------------------
# Answer rendering
# ---------------------------------------------------------------------------
def _anchor(url: str) -> str:
    """A visible markdown link with ``rel="noopener noreferrer"``.

    The citation is rendered as an ordinary inline link, not a hover or a
    drawer, because FR-8.5 requires the source to be visible in the answer.
    """
    if not url.lower().startswith(("http://", "https://")):
        return url
    safe = (
        url.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
    return f'<a href="{safe}" target="_blank" rel="noopener noreferrer">{safe}</a>'


def answer_markdown(payload: Any) -> str:
    """``payload.text`` with the source URL turned into a visible link."""
    text = payload.text or ""
    url = getattr(payload, "source_url", None)
    if url and url in text:
        text = text.replace(url, _anchor(url), 1)
    return text


def _render_chunks(payload: Any) -> None:
    """The RAG trace: what retrieval actually returned, and why it ranked."""
    trace = getattr(payload, "trace", None)
    chunks = list(getattr(trace, "chunks", None) or [])
    with st.expander("Show retrieved chunks (RAG trace)", expanded=False):
        if not chunks:
            st.caption("No chunk cleared the similarity floor for this question.")
            return
        st.caption(
            f"{len(chunks)} chunk(s) · top score {trace.top_score:.3f} · "
            f"floor {trace.tau:.2f} · scheme filter "
            f"{trace.scheme_filter or 'none'}"
        )
        for rank, item in enumerate(chunks, 1):
            chunk = item.chunk
            boost = " (field_type boost applied)" if item.boosted else ""
            preview = (chunk.text or "")[:_PREVIEW_CHARS]
            st.markdown(
                f"**{rank}. {chunk.scheme}** · `{chunk.field_type}` · "
                f"score **{item.similarity:.3f}** (raw {item.raw_similarity:.3f}){boost}"
            )
            st.caption(preview)
            st.caption(chunk.source_url)


def render_payload(payload: Any) -> None:
    """Draw one assistant turn inside the chat thread."""
    if payload.route is Route.PII:
        # A rejection of the input, not an answer: warn rather than info, and
        # never show a citation. Streamlit wants a real emoji, not a
        # ":shortcode:" - a shortcode raises StreamlitAPIException on load.
        st.warning(answer_markdown(payload), icon="\U0001f6ab")
        return

    if payload.route in REFUSAL_ROUTES:
        st.info(answer_markdown(payload))
    else:
        st.markdown(answer_markdown(payload), unsafe_allow_html=True)

    if getattr(payload, "degraded", False):
        st.caption("Degraded response - the answer may not be fully grounded.")

    _render_chunks(payload)


# ---------------------------------------------------------------------------
# UI
# ---------------------------------------------------------------------------
def _example_buttons() -> None:
    """Three clickable examples that prefill the chat box."""
    for column, question in zip(st.columns(len(EXAMPLE_QUESTIONS)), EXAMPLE_QUESTIONS):
        if column.button(question, key=f"example-{question}"):
            st.session_state["pending_query"] = question


def _append_user(query: str) -> None:
    st.session_state.messages.append({"role": "user", "text": query})


def _ask_and_record(query: str, ask_fn: Callable[[str], Any]) -> None:
    """Run the pipeline, record the turn, and never invent an answer on failure."""
    try:
        payload = ask_fn(query)
    except Exception as exc:  # noqa: BLE001 - I6: no ungrounded fallback
        st.session_state.messages.append(
            {
                "role": "assistant",
                "text": "I couldn't answer right now. Please try again.",
                "route": None,
                "trace": None,
                "error": f"{type(exc).__name__}",
            }
        )
        return
    st.session_state.messages.append(
        {
            "role": "assistant",
            "text": payload.text,
            "route": payload.route,
            "trace": getattr(payload, "trace", None),
            "payload": payload,
        }
    )


def _render_thread() -> None:
    for message in st.session_state.messages:
        with st.chat_message(message["role"]):
            if message["role"] == "user":
                st.markdown(message["text"])
                continue
            payload = message.get("payload")
            if payload is None:
                st.warning(message["text"], icon="\U0001f6ab")
                continue
            render_payload(payload)


def streamlit_ui(ask_fn: Callable[[str], Any] = ask) -> None:
    """The whole chat UI. ``ask_fn`` is injected so tests can drive it."""
    st.set_page_config(page_title=PRODUCT_NAME, layout="centered")

    if "messages" not in st.session_state:
        st.session_state.messages = []

    # 1. Header
    st.title(PRODUCT_NAME)
    st.caption(corpus_summary())

    # 2. Disclaimer, always visible, above the chat
    st.warning(DISCLAIMER)

    if store_is_empty():
        st.error(INGEST_HINT)
        return

    # 3. Example questions
    st.caption("Try one of these:")
    _example_buttons()

    # 4/5. The thread, then the new question
    typed = st.chat_input("Ask a factual question about the 5 HDFC schemes")
    pending = st.session_state.pop("pending_query", None)
    query = typed or pending
    if query:
        _append_user(query)
        _ask_and_record(query, ask_fn)

    _render_thread()


if __name__ == "__main__":
    streamlit_ui()
